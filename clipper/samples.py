"""Generate a tiny synthetic campaign so the pipeline can be tested without
real footage.

This is deliberately honest about what it is: a 9:16 test clip with burned-in
captions rendered from the *default* style profile, plus a mock "podcast" raw
file. It exercises the plumbing (probe -> scan -> captions -> render -> viewer)
with a few hundred kilobytes instead of a few hundred megabytes.

For real style learning you want real references - drop them in
campaigns/<name>/references (or samples/local/<campaign>/references).

    python -m clipper samples
"""
from __future__ import annotations

import subprocess
from pathlib import Path

from . import config
from .asr.base import Word
from .captions.ass import write_ass
from .captions.cues import group_words
from .captions.render import escape_filter_path
from .ffmpeg import ffmpeg_exe, probe
from .util import log

# a soft "podcast studio" backdrop: flat colour, a panel, a drifting light, vignette
BG = ("color=c=0x141a24:s=1080x1920:d=7.5,"
      "drawbox=x=140:y=300:w=800:h=800:color=0x22304a@1:t=fill,"
      "drawbox=x='140+40*sin(2*PI*t/7.5)':y=340:w=320:h=320:color=0x35507a@1:t=fill,"
      "vignette=PI/5")
# a low tone with a slow tremolo (stands in for a voice track)
TONE = "sine=frequency=180:sample_rate=48000:duration=7.5,aeval=val(0)*0.06+0.02*sin(2*PI*40*t):c=same"

SCRIPT = [
    ("This", 0.30, 0.55), ("is", 0.55, 0.72), ("the", 0.72, 0.95),
    ("clipper", 0.95, 1.45), ("pipeline.", 1.45, 2.10),
    ("Words", 2.35, 2.75), ("turn", 2.75, 3.05), ("into", 3.05, 3.35),
    ("styled", 3.35, 3.85), ("captions.", 3.85, 4.60),
    ("Nine", 4.85, 5.20), ("by", 5.20, 5.45), ("sixteen,", 5.45, 6.05),
    ("ready", 6.05, 6.45), ("to", 6.45, 6.70), ("post.", 6.70, 7.30),
]


def demo_words() -> list[Word]:
    return [Word(text=t, start=s, end=e, prob=1.0, source="fixture") for t, s, e in SCRIPT]


def _render(dst: Path, *, ass_path: Path | None = None, duration: float = 7.5) -> Path:
    args = [ffmpeg_exe(), "-y", "-v", "error", "-nostdin",
            "-f", "lavfi", "-i", BG, "-f", "lavfi", "-i", TONE]
    if ass_path is not None:
        args += ["-vf", f"subtitles=filename='{escape_filter_path(ass_path)}'"]
    args += ["-t", f"{duration}", "-c:v", "libx264", "-preset", "veryfast", "-crf", "24",
             "-pix_fmt", "yuv420p", "-r", "30", "-c:a", "aac", "-b:a", "128k",
             "-movflags", "+faststart", str(dst)]
    proc = subprocess.run(args, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"sample render failed: {proc.stderr.strip()[-400:]}")
    return dst


def make_demo_campaign(force: bool = False) -> Path:
    campaign = config.SAMPLES / "campaign_demo"
    refs = campaign / "references"
    raw = campaign / "raw"
    refs.mkdir(parents=True, exist_ok=True)
    raw.mkdir(parents=True, exist_ok=True)
    ref_video = refs / "reference_01.mp4"
    raw_video = raw / "raw_01.mp4"
    if ref_video.exists() and raw_video.exists() and not force:
        log.info("sample campaign already exists", path=str(campaign))
        return campaign

    cues = group_words(demo_words(), max_words=4, max_chars=22, max_lines=1)
    ass_ref = campaign / "_reference.ass"
    write_ass(ass_ref, cues, config.DEFAULT_STYLE, width=1080, height=1920)
    log.info("rendering sample reference", out=ref_video.name)
    _render(ref_video, ass_path=ass_ref)
    ass_ref.unlink(missing_ok=True)
    log.info("rendering sample raw footage", out=raw_video.name)
    _render(raw_video)

    (campaign / "README.md").write_text(
        "# campaign_demo (synthetic)\n\n"
        "Generated by `python -m clipper samples`.\n\n"
        "- `references/reference_01.mp4` - mock reference clip, captions in the default style\n"
        "- `raw/raw_01.mp4` - mock raw footage (a tone, not speech: real ASR needs real speech)\n\n"
        "Replace with real material under `campaigns/<name>/` whenever you like.\n",
        encoding="utf-8")
    for p in (ref_video, raw_video):
        info = probe(p)
        log.info("sample", file=p.name, size=f"{p.stat().st_size / 1024:.0f} KB",
                 res=f"{info.width}x{info.height}", dur=f"{info.duration:.1f}s")
    return campaign
