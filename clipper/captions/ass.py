"""Turn cues + a style profile into an .ass subtitle file (libass renders it).

This is where "styled to match the reference" becomes concrete: font size,
colours, outline, position, karaoke highlight and the pop animation all come
from the style profile that stage 1 extracted from the campaign references.

Two looks are supported, both from the same cue data:

  line : the whole cue is on screen, words light up as they are spoken
         (karaoke `\\k` tags; ASS PrimaryColour = highlight, Secondary = base)
  word : one event per word, whole cue visible with the active word recoloured
         (the classic "big word-by-word" short-form look)
"""
from __future__ import annotations

from pathlib import Path

from ..util.timecode import fmt_ass
from .cues import Cue


def ass_color(value: str | list[int] | tuple[int, int, int], alpha: int = 0) -> str:
    """'#RRGGBB' (or [r,g,b]) -> ASS '&HAABBGGRR'."""
    if isinstance(value, str):
        v = value.lstrip("#")
        r, g, b = int(v[0:2], 16), int(v[2:4], 16), int(v[4:6], 16)
    else:
        r, g, b = (int(c) for c in value[:3])
    return f"&H{alpha:02X}{b:02X}{g:02X}{r:02X}"


def _escape(text: str) -> str:
    return text.replace("{", "(").replace("}", ")").replace("\n", " ")


def _autofit(font_size: int, cues: list[Cue], width: int, margin_lr: int) -> int:
    """Shrink the font when the longest line would overflow the safe area.

    A rough width model (0.52 em average advance for a bold geometric sans) is
    plenty: the goal is to never clip a caption, not to beat a font metric.
    """
    longest = 0
    for cue in cues:
        for line in (cue.lines or []):
            longest = max(longest, len(" ".join(line)))
        if not cue.lines:
            longest = max(longest, len(cue.text))
    safe = max(1, width - 2 * margin_lr)
    estimated = longest * font_size * 0.52
    if estimated <= safe or estimated <= 0:
        return font_size
    fitted = int(round(font_size * (safe / estimated) * 0.98))
    fitted = max(int(font_size * 0.55), fitted)  # never go absurdly small
    return fitted


def _align_from_anchor(anchor: str) -> int:
    return {"bottom_center": 2, "bottom_left": 1, "bottom_right": 3,
            "center": 5, "top_center": 8}.get(anchor or "bottom_center", 2)


def build_ass(cues: list[Cue], style: dict, *, width: int = 1080, height: int = 1920,
              mode: str | None = None) -> str:
    cap = (style or {}).get("captions", {}) or {}
    karaoke = cap.get("karaoke", {}) or {}
    pos = cap.get("position", {}) or {}
    anim = cap.get("animation", {}) or {}

    scale = height / 1920.0
    font_size = int(round(float(cap.get("font_size_ass") or 96) * scale))
    margin_lr_probe = int(round(width * 0.055))
    font_size = _autofit(font_size, cues, width, margin_lr_probe)
    outline = max(0, int(round(float(cap.get("outline_width") or 5) * scale)))
    shadow = max(0, int(round(float(cap.get("shadow") or 0) * scale)))
    base_color = ass_color(cap.get("primary_color") or "#FFFFFF")
    highlight = ass_color(karaoke.get("highlight_color") or cap.get("highlight_color") or "#FFE14D")
    outline_color = ass_color(cap.get("outline_color") or "#000000")
    primary = highlight if karaoke.get("enabled", True) else base_color
    secondary = base_color
    alignment = _align_from_anchor(pos.get("anchor", "bottom_center"))
    cy = float(pos.get("cy") or 0.80)
    margin_lr = int(round(width * 0.055))
    line_h = font_size * 1.18
    if alignment in (1, 2, 3):
        margin_v = int(round(max(0.0, height * (1.0 - cy) - line_h / 2)))
    elif alignment in (7, 8, 9):
        margin_v = int(round(max(0.0, height * cy - line_h / 2)))
    else:
        margin_v = 0
    font_name = cap.get("font_family") or "Arial"
    bold = 1 if (cap.get("font_weight") or "bold").lower() in ("bold", "700", "800", "900") else 0
    italic = 1 if cap.get("italic") else 0
    mode = (mode or cap.get("mode") or "line").lower()
    in_anim = (anim.get("in") or "none").lower()
    anim_ms = int(float(anim.get("duration") or 0.12) * 1000)

    header = f"""[Script Info]
; generated by clipper - do not edit by hand
ScriptType: v4.00+
PlayResX: {width}
PlayResY: {height}
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Cap,{font_name},{font_size},{primary},{secondary},{outline_color},&H64000000,{bold},{italic},0,0,100,100,0,0,1,{outline},{shadow},{alignment},{margin_lr},{margin_lr},{margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    lines: list[str] = []
    for cue in cues:
        if not cue.words:
            continue
        if mode == "word":
            lines.extend(_word_events(cue, cap, base_color, highlight, anim_ms, in_anim))
        else:
            lines.append(_line_event(cue, cap, karaoke, anim_ms, in_anim))
    return header + "\n".join(lines) + "\n"


def _apply_casing(text: str, cap: dict) -> str:
    casing = (cap.get("casing") or "").lower()
    if casing in ("upper", "uppercase", "caps"):
        return text.upper()
    if casing in ("lower", "lowercase"):
        return text.lower()
    return text


def _line_event(cue: Cue, cap: dict, karaoke: dict, anim_ms: int, in_anim: str) -> str:
    tags = []
    if in_anim == "pop":
        tags.append(rf"\fscx82\fscy82\t(0,{anim_ms},\fscx100\fscy100)")
    elif in_anim == "fade":
        tags.append(rf"\fad({anim_ms},{anim_ms})")
    body_parts: list[str] = []
    k_on = bool(karaoke.get("enabled", True))
    for w in cue.words:
        token = _escape(_apply_casing(w.text, cap))
        if k_on:
            cs = max(1, int(round(w.duration * 100)))
            body_parts.append(rf"{{\k{cs}}}{token}")
        else:
            body_parts.append(token)
    body = " ".join(body_parts)
    # line breaks come from the cue layout, unless the caller asked for one line
    if len(cue.lines) > 1:
        rebuilt: list[str] = []
        idx = 0
        for ln in cue.lines:
            chunk = []
            for _ in ln:
                if k_on and idx < len(cue.words):
                    cs = max(1, int(round(cue.words[idx].duration * 100)))
                    chunk.append(rf"{{\k{cs}}}{_escape(_apply_casing(cue.words[idx].text, cap))}")
                elif idx < len(cue.words):
                    chunk.append(_escape(_apply_casing(cue.words[idx].text, cap)))
                idx += 1
            rebuilt.append(" ".join(chunk))
        body = r"\N".join(rebuilt)
    prefix = "".join(t for t in tags if t)
    override = f"{{{prefix}}}" if prefix else ""
    return f"Dialogue: 0,{fmt_ass(cue.start)},{fmt_ass(cue.end)},Cap,,0,0,0,,{override}{body}"


def _word_events(cue: Cue, cap: dict, base_color: str, highlight: str,
                 anim_ms: int, in_anim: str) -> list[str]:
    out: list[str] = []
    for i, word in enumerate(cue.words):
        parts = []
        for j, w in enumerate(cue.words):
            token = _escape(_apply_casing(w.text, cap))
            if j == i:
                anim = ""
                if in_anim == "pop":
                    anim = rf"\fscx108\fscy108\t(0,{anim_ms},\fscx100\fscy100)"
                parts.append(rf"{{\c{highlight}{anim}}}{token}{{\c{base_color}}}")
            else:
                parts.append(token)
        start, end = word.start, word.end
        if i + 1 < len(cue.words) and cue.words[i + 1].start - end < 0.02:
            end = max(end, cue.words[i + 1].start)
        out.append(f"Dialogue: 0,{fmt_ass(start)},{fmt_ass(end)},Cap,,0,0,0,,{' '.join(parts)}")
    return out


def write_ass(path: str | Path, cues: list[Cue], style: dict, *, width: int = 1080,
              height: int = 1920, mode: str | None = None) -> Path:
    text = build_ass(cues, style, width=width, height=height, mode=mode)
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")
    return p
